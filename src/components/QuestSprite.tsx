export type SpriteName = keyof typeof SPRITES

export function QuestSprite({ name, className }: { name: SpriteName; className?: string }) {
  const rows = SPRITES[name]
  return (
    <svg className={`sprite ${className ?? ''}`} viewBox="0 0 9 9" shapeRendering="crispEdges" aria-hidden="true">
      {rows.flatMap((row, y) => [...row].map((c, x) => (c === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null)))}
    </svg>
  )
}
